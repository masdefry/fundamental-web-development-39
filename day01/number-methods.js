// .toString()  : Konversi number menjadi string
const point = 1000;
console.log(point);
console.log(point.toString());

// .toFixed()   : Pembulatan sesuai aturan matematika
const decimal = 3.4;
console.log(decimal.toFixed());

const stringNumber = '123xzy321';
// Number       : Konversi dari string menjadi number
console.log(Number(stringNumber));

// parseInt     : Konversi dari string menjadi number
console.log(parseInt(stringNumber));

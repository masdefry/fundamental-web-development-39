/*
    COMPARISON OPERATORS    : Operator pembanding. Menghasilkan nilai akhir berupa boolean (true/false)
*/

// >
console.log(10 > 5);

// >=
console.log(10 >= 10);

// <
console.log(3 < 1);

// <=
console.log(5 <= 10);

// ==   : Komparasi nilai saja
console.log(5 == 5);
console.log(5 == '5');

// ===  : Komparasi nilai sekaligus tipe data
console.log(5 === '5');
console.log(5 === Number('5'));

// !=   : Komparasi nilai saja
console.log(3 != '3');

// !==  : Komparasi nilai sekaigus tipe data
console.log(3 !== '3');
